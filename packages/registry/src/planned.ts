import type { CategoryId } from '@niftyfix/tool-sdk';

/**
 * Every tool on the roadmap (from docs/tool-catalogue-v3.md, with duplicates
 * merged), by workspace.
 *
 * Shown on category hubs as "coming soon" without a link: a planned tool gets
 * its own page only when it is built, because an empty page helps no one and
 * hurts search ranking. A built tool with the same category and slug replaces
 * its planned entry. The slug is the tool's future URL (keep it stable) and
 * follows how people search ("merge-pdf", not "pdf-merger").
 */
export type ExecutionMode =
  /** Runs entirely on the user's device. */
  | 'browser'
  /** Needs our servers (e.g. Office rendering, accounts, sending email). */
  | 'server'
  /** Needs an AI model; compute cost and quality to be evaluated. */
  | 'ai'
  /** Blocked on a legal, licence, codec or terms-of-service review. */
  | 'gated';

export interface PlannedTool {
  category: CategoryId;
  slug: string;
  name: string;
  mode: ExecutionMode;
}

type Row = [slug: string, name: string, mode?: ExecutionMode];

const tools = (category: CategoryId, rows: Row[]): PlannedTool[] =>
  rows.map(([slug, name, mode = 'browser']) => ({ category, slug, name, mode }));

