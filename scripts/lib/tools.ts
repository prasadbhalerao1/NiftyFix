import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { PLANNED_TOOLS } from '@niftyfix/registry';
import { CATEGORIES, CATEGORY_IDS } from '@niftyfix/tool-sdk';

export const ROOT = resolve(import.meta.dirname, '..', '..');
export const TOOLS_DIR = join(ROOT, 'tools');
export const GENERATED_FILE = join(TOOLS_DIR, 'registry.generated.ts');
export const TOOL_LIST_FILE = join(ROOT, 'docs', 'tool-list.md');
export const REQUIRED_FILES = ['manifest.ts', 'content.ts', 'processor.ts', 'ui.tsx'] as const;

/** Interactive tools (no file input) compute in their UI and have no processor. */
export const isInteractive = (dir: string): boolean =>
  /kind:\s*'interactive'/.test(readFileSync(join(TOOLS_DIR, dir, 'manifest.ts'), 'utf8'));

export const requiredFiles = (dir: string): readonly string[] =>
  isInteractive(dir) ? REQUIRED_FILES.filter((file) => file !== 'processor.ts') : REQUIRED_FILES;

/** Every "category/slug" directory under tools/ that contains a manifest. */
export function discoverToolDirs(): string[] {
  const dirs: string[] = [];
  for (const category of readdirSync(TOOLS_DIR, { withFileTypes: true })) {
    if (!category.isDirectory() || category.name === 'node_modules') continue;
    for (const tool of readdirSync(join(TOOLS_DIR, category.name), { withFileTypes: true })) {
      if (
        tool.isDirectory() &&
        existsSync(join(TOOLS_DIR, category.name, tool.name, 'manifest.ts'))
      ) {
        dirs.push(`${category.name}/${tool.name}`);
      }
    }
  }
  return dirs.sort();
}

export function renderRegistry(dirs: readonly string[]): string {
  const imports = dirs.flatMap((dir, i) => [
    `import content${i} from './${dir}/content';`,
    `import manifest${i} from './${dir}/manifest';`,
  ]);
  const entries = dirs.map(
    (dir, i) => `  { dir: '${dir}', manifest: manifest${i}, content: content${i} },`,
  );
  return [
    '// GENERATED by scripts/generate-registry.ts: do not edit. Run `pnpm registry`.',
    '// Imports manifests and content only; tool code is loaded lazily via loaders.ts.',
    "import type { ToolEntry } from '@niftyfix/registry';",
    ...imports,
    '',
    'export const TOOL_ENTRIES: readonly ToolEntry[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

/** Every planned and built tool as a checklist, ticked when its manifest is live. */
export function renderToolList(dirs: readonly string[]): string {
  const manifests = new Map(
    dirs.map((dir) => [dir, readFileSync(join(TOOLS_DIR, dir, 'manifest.ts'), 'utf8')]),
  );
  const live = (dir: string): boolean => /status:\s*'live'/.test(manifests.get(dir) ?? '');
  const sections: string[] = [];
  let done = 0;
  let total = 0;
  for (const category of CATEGORY_IDS) {
    const planned = PLANNED_TOOLS.filter((tool) => tool.category === category);
    const plannedSlugs = new Set(planned.map((tool) => tool.slug));
    const rows = [
      ...planned.map((tool) => ({
        name: tool.name,
        slug: tool.slug,
        mode: tool.mode,
        done: live(`${category}/${tool.slug}`),
      })),
      ...dirs
        .map((dir) => ({ dir, slug: dir.slice(dir.indexOf('/') + 1) }))
        .filter(({ dir, slug }) => dir.startsWith(`${category}/`) && !plannedSlugs.has(slug))
        .map(({ dir, slug }) => ({
          name: /name:\s*(['"])(.*?)\1/.exec(manifests.get(dir) ?? '')?.[2] ?? dir,
          slug,
          mode: 'browser',
          done: live(dir),
        })),
    ];
    if (rows.length === 0) continue;
    const ticked = rows.filter((row) => row.done).length;
    done += ticked;
    total += rows.length;
    sections.push(
      `## ${CATEGORIES[category].name} (${ticked} of ${rows.length})`,
      '',
      ...rows.map(
        (row) =>
          `- [${row.done ? 'x' : ' '}] ${row.name} (\`${row.slug}\`${row.mode === 'browser' ? '' : `, ${row.mode}`})`,
      ),
      '',
    );
  }
  return [
    '# Tool list',
    '',
    'GENERATED by scripts/generate-registry.ts from `packages/registry/src/planned.ts` and the built tools: do not edit. Run `pnpm registry`.',
    '',
    `**${done} of ${total} tools live.** A tool is ticked when its manifest status is live.`,
    '',
    ...sections,
  ].join('\n');
}

const writeIfChanged = (path: string, next: string): boolean => {
  if (existsSync(path) && readFileSync(path, 'utf8') === next) return false;
  writeFileSync(path, next);
  return true;
};

export function writeRegistry(): { changed: boolean } {
  const dirs = discoverToolDirs();
  const registry = writeIfChanged(GENERATED_FILE, renderRegistry(dirs));
  const list = writeIfChanged(TOOL_LIST_FILE, renderToolList(dirs));
  return { changed: registry || list };
}
